"""Generate a Gazebo world of white bowls on grass plus a JSON ground-truth manifest.

    python tools/make_world.py --name sparse --seed 1 --bowls 12 --field 120 80
    python tools/make_world.py --name dense  --seed 2 --bowls 60 --field 120 80

Writes sim/worlds/bowl_field_<name>.sdf and sim/worlds/bowl_field_<name>.json.
The JSON is the single source of truth for scoring. Positions are metres in the world
frame (ENU, origin at the takeoff point) with latitude and longitude derived from the
world's spherical coordinates. The origin is PX4's default SITL location, not a real
operating site.

Field extents are centred on the origin. Bowls are kept at least --min-sep metres apart
and at least 3 m from the field edge so the survey footprint always covers them.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import random

ORIGIN_LAT = 47.397971057728974   # PX4 default SITL origin (Zurich)
ORIGIN_LON = 8.546163739800146
ORIGIN_ALT = 0.0
EARTH_R = 6371000.0
TEXTURE_TILE_M = 16.0             # one 4096 px grass texture tile covers this many metres (0.39 cm/px)
GROUND_SIZE_M = 400.0


def enu_to_latlon(x: float, y: float) -> tuple[float, float]:
    """Small-offset flat-earth conversion, good to millimetres at field scale."""
    lat = ORIGIN_LAT + math.degrees(y / EARTH_R)
    lon = ORIGIN_LON + math.degrees(x / (EARTH_R * math.cos(math.radians(ORIGIN_LAT))))
    return lat, lon


def place_bowls(n: int, w: float, h: float, min_sep: float, rng: random.Random, margin: float = 3.0):
    pts: list[tuple[float, float]] = []
    tries = 0
    while len(pts) < n:
        tries += 1
        if tries > 200000:
            raise SystemExit(f"could not place {n} bowls with min-sep {min_sep} in {w}x{h} m")
        x = rng.uniform(-w / 2 + margin, w / 2 - margin)
        y = rng.uniform(-h / 2 + margin, h / 2 - margin)
        if all(math.hypot(x - px, y - py) >= min_sep for px, py in pts):
            pts.append((round(x, 3), round(y, 3)))
    return pts


def ground_mesh(path: str) -> None:  # written into sim/models/grass_ground
    """A single quad with UVs that repeat the grass texture every TEXTURE_TILE_M metres."""
    half = GROUND_SIZE_M / 2
    rep = GROUND_SIZE_M / TEXTURE_TILE_M
    with open(path, "w") as f:
        f.write("# ground quad generated by tools/make_world.py\n")
        f.write(f"v -{half} -{half} 0\nv {half} -{half} 0\nv {half} {half} 0\nv -{half} {half} 0\n")
        f.write(f"vt 0 0\nvt {rep} 0\nvt {rep} {rep}\nvt 0 {rep}\nvn 0 0 1\n")
        f.write("f 1/1/1 2/2/1 3/3/1\nf 1/1/1 3/3/1 4/4/1\n")


