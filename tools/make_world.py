def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--name", required=True, help="suffix for bowl_field_<name>")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--bowls", type=int, default=12)
    ap.add_argument("--field", type=float, nargs=2, default=(120.0, 80.0), metavar=("W", "H"), help="field size in metres, centred on the origin")
    ap.add_argument("--min-sep", type=float, default=2.0, help="minimum bowl spacing in metres")
    ap.add_argument("--out-dir", default="sim/worlds")
    a = ap.parse_args()

    rng = random.Random(a.seed)
    bowls = place_bowls(a.bowls, a.field[0], a.field[1], a.min_sep, rng)
    os.makedirs(a.out_dir, exist_ok=True)
    ground_mesh(os.path.join(os.path.dirname(a.out_dir.rstrip("/")), "models", "grass_ground", "ground_400m.obj"))
    world_name = f"bowl_field_{a.name}"
    # model:// URIs resolve through GZ_SIM_RESOURCE_PATH, which scripts/env.sh points at sim/models
    sdf = world_sdf(world_name, bowls)
    with open(os.path.join(a.out_dir, world_name + ".sdf"), "w") as f:
        f.write(sdf)
    manifest = {
        "world": world_name,
        "seed": a.seed,
        "field_m": list(a.field),
        "origin": {"lat": ORIGIN_LAT, "lon": ORIGIN_LON, "alt": ORIGIN_ALT},
        "bowl_diameter_m": 0.16,
        "density_per_ha": round(a.bowls / (a.field[0] * a.field[1] / 10000.0), 3),
        "bowls": [
            {"id": i, "x": x, "y": y, **dict(zip(("lat", "lon"), enu_to_latlon(x, y)))}
            for i, (x, y) in enumerate(bowls)
        ],
    }
    with open(os.path.join(a.out_dir, world_name + ".json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print(f"wrote {world_name}.sdf and .json: {a.bowls} bowls on {a.field[0]:.0f}x{a.field[1]:.0f} m "
          f"({manifest['density_per_ha']} per ha)")


if __name__ == "__main__":
    main()
